"use client";

import React, { useEffect, useRef, useState } from "react";
import { X, Minus, Maximize2, Trash2, MessageSquare } from "lucide-react";
import { ChatMessage, CitationItem, DashboardStatus } from "../types";
import { FloatingPanel } from "./FloatingPanel";
import { DialogueThread } from "./DialogueThread";
import { useVoiceSnapshot } from "../lib/voice/voiceStore";

interface ChatHUDProps {
  messages: ChatMessage[];
  onSendMessage: (text: string) => void;
  onStopGenerating: () => void;
  onCitationClick: (citation: CitationItem) => void;
  isLoading: boolean;
  isOpen: boolean;
  onClose: () => void;
  onClearMessages?: () => void;
  theme?: "dark" | "light";
  onToggleVoice: () => void;
  onSpeakMessage: (msg: ChatMessage) => void;
  onStopSpeaking: () => void;
  speakingMessageId: string | null;
  onCreateDashboard: (msg: ChatMessage) => void;
  onOpenDashboard: (dashboardId: string) => void;
  dashboardStatus: Record<string, DashboardStatus>;
  /** Suggested questions generated by the backend from this entity's documents. */
  prompts?: string[];
}

const VOICE_PHASE_LABEL: Record<string, string> = {
  idle: "Ready",
  listening: "Listening",
  transcribing: "Transcribing",
  thinking: "Searching records",
  speaking: "Speaking",
};

export function ChatHUD({
  messages,
  onSendMessage,
  onCitationClick,
  isOpen,
  onClose,
  onClearMessages,
  theme = "light",
  onSpeakMessage,
  onStopSpeaking,
  speakingMessageId,
  prompts = [],
}: ChatHUDProps) {
  const [isMinimized, setIsMinimized] = useState(false);
  const scrollRef = useRef<HTMLDivElement | null>(null);
  const stickToBottom = useRef(true);
  const voice = useVoiceSnapshot();
  const isLight = theme === "light";

  // Follow streaming output while the reader is at the bottom
  useEffect(() => {
    const el = scrollRef.current;
    if (el && stickToBottom.current) el.scrollTop = el.scrollHeight;
  }, [messages, isOpen, isMinimized]);

  if (!isOpen) return null;

  const exchangeCount = messages.filter((m) => m.sender === "user").length;

  if (isMinimized) {
    return (
      <FloatingPanel
        id="dialogue-pill"
        theme={theme}
        resize="none"
        minW={200}
        minH={44}
        defaultRect={(vw, vh) => ({ x: vw - 240, y: vh - 100, w: 220, h: 44 })}
      >
        <button
          onClick={() => setIsMinimized(false)}
          aria-label="Restore dialogue"
          className={`w-full h-full flex items-center gap-2.5 px-4 rounded-md border shadow-md ${
            isLight ? "bg-white text-slate-900 border-slate-200" : "bg-[#0F172A] text-white border-slate-700"
          }`}
        >
          <MessageSquare className="w-4 h-4 text-blue-600" aria-hidden />
          <span className="text-[13px] font-medium">Dialogue</span>
          <span className="text-[12px] text-slate-500 tabular-nums">{exchangeCount}</span>
          <Maximize2 className="w-3.5 h-3.5 opacity-50 ml-auto" aria-hidden />
        </button>
      </FloatingPanel>
    );
  }

  const iconBtn = `p-1.5 rounded transition-colors ${
    isLight ? "text-slate-500 hover:text-slate-900 hover:bg-slate-100" : "text-slate-400 hover:text-white hover:bg-slate-800"
  }`;
  const status =
    voice.conversation && voice.phase !== "idle"
      ? `Voice · ${voice.error ? "Error" : VOICE_PHASE_LABEL[voice.phase] || "Ready"}`
      : "Answers grounded in your authorised records";

  return (
    <FloatingPanel
      id="dialogue"
      theme={theme}
      ariaLabel="Dialogue"
      minW={340}
      minH={360}
      defaultRect={(vw, vh) => {
        const w = Math.min(460, vw - 32);
        return { x: vw - w - 16, y: 120, w, h: Math.max(380, vh - 120 - 100) };
      }}
    >
      <aside
        className={`w-full h-full flex flex-col rounded-lg border shadow-lg overflow-hidden ${
          isLight ? "bg-white border-slate-200 text-slate-900" : "bg-[#0F172A] border-slate-700 text-slate-100"
        }`}
      >
        <div
          data-drag-handle
          title="Drag to move · double-click to reset"
          className={`px-4 py-3 border-b flex items-center justify-between cursor-grab active:cursor-grabbing touch-none select-none ${
            isLight ? "border-slate-200" : "border-slate-800"
          }`}
        >
          <div className="pointer-events-none min-w-0">
            <h2 className="text-[14px] font-semibold">Dialogue</h2>
            <p className={`text-[12px] truncate ${isLight ? "text-slate-500" : "text-slate-400"}`}>{status}</p>
          </div>
          <div className="flex items-center gap-0.5">
            {onClearMessages && messages.length > 0 && (
              <button onClick={onClearMessages} aria-label="Clear dialogue" title="Clear dialogue" className={iconBtn}>
                <Trash2 className="w-4 h-4" />
              </button>
            )}
            <button onClick={() => setIsMinimized(true)} aria-label="Minimise dialogue" title="Minimise" className={iconBtn}>
              <Minus className="w-4 h-4" />
            </button>
            <button onClick={onClose} aria-label="Close dialogue" title="Close" className={iconBtn}>
              <X className="w-4 h-4" />
            </button>
          </div>
        </div>

        <div
          ref={scrollRef}
          onScroll={(e) => {
            const el = e.currentTarget;
            stickToBottom.current = el.scrollHeight - el.scrollTop - el.clientHeight < 60;
          }}
          className="flex-1 overflow-y-auto px-4 py-4 select-text"
        >
          {messages.length === 0 ? (
            <div className="space-y-4">
              <div>
                <h3 className="text-[14px] font-semibold">No questions yet</h3>
                <p className={`text-[13px] leading-relaxed mt-1 ${isLight ? "text-slate-500" : "text-slate-400"}`}>
                  Ask about holdings, statements, tax notices or trust distributions. Answers cite the records they come from.
                </p>
              </div>
              {prompts.length > 0 && (
                <div>
                  <div className="text-[11px] font-semibold uppercase tracking-wide text-slate-500 mb-1.5">
                    Suggested from your documents
                  </div>
                  <ul className={`divide-y rounded-md border ${isLight ? "divide-slate-100 border-slate-200" : "divide-slate-800 border-slate-800"}`}>
                    {prompts.slice(0, 4).map((p) => (
                      <li key={p}>
                        <button
                          type="button"
                          onClick={() => onSendMessage(p)}
                          className={`w-full text-left px-3 py-2 text-[13px] ${isLight ? "hover:bg-slate-50" : "hover:bg-slate-800/60"}`}
                        >
                          {p}
                        </button>
                      </li>
                    ))}
                  </ul>
                </div>
              )}
            </div>
          ) : (
            <DialogueThread
              messages={messages}
              theme={theme}
              onCitationClick={onCitationClick}
              onSpeakMessage={onSpeakMessage}
              onStopSpeaking={onStopSpeaking}
              speakingMessageId={speakingMessageId}
              compact
            />
          )}
        </div>
      </aside>
    </FloatingPanel>
  );
}
